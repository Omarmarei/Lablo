/**
 * The battery's media (RELAY step 15c): the lab server's `/__lab/media` answer
 * (apps/mock-provider/src/lab-media.ts), checked before any check trusts it. The URLs carry the
 * mock's test account, so no record ever holds one.
 */

/** The MIME types the battery asks an engine about (`canPlayType`). */
export const CONTAINER_MIME: Readonly<Record<'ts' | 'hls' | 'mp4' | 'mkv', string>> = {
  ts: 'video/mp2t',
  hls: 'application/vnd.apple.mpegurl',
  mp4: 'video/mp4',
  mkv: 'video/x-matroska',
};
export const HEVC_MIME = 'video/mp4; codecs="hvc1.1.6.L150.B0"';
export const AC3_MIME = 'audio/mp4; codecs="ac-3"';
export const EAC3_MIME = 'audio/mp4; codecs="ec-3"';

export const LAB_MEDIA_IDS = ['live-ts', 'live-hls', 'redirect-ts', 'redirect-hls', 'stall-ts', 'stall-vod', 'hevc-4k', 'multi-audio', 'subs-mkv', 'subs-mp4'] as const;
export type LabMediaId = (typeof LAB_MEDIA_IDS)[number];

export interface MediaTrackInfo {
  readonly lang: string;
  readonly codec: string;
  readonly channels: number;
}

export interface LabMediaItem {
  readonly url: string;
  readonly kind: 'live' | 'vod';
  readonly container: 'ts' | 'hls' | 'mp4' | 'mkv';
  readonly fault: string | null;
  readonly video: { readonly codec: string; readonly width: number; readonly height: number } | null;
  readonly audio: readonly MediaTrackInfo[] | null;
  readonly subtitles: ReadonlyArray<{ readonly lang: string; readonly codec: string }> | null;
}

export interface LabMedia {
  /** `files` (generated by `pnpm mock:media`) or `placeholder` (bytes nothing plays). */
  readonly media: string;
  readonly items: Partial<Record<LabMediaId, LabMediaItem>>;
}

const isObject = (value: unknown): value is Record<string, unknown> => typeof value === 'object' && value !== null && !Array.isArray(value);

function trackList(value: unknown): MediaTrackInfo[] | null {
  if (!Array.isArray(value)) return null;
  const out: MediaTrackInfo[] = [];
  for (const t of value) {
    if (!isObject(t) || typeof t.lang !== 'string' || typeof t.codec !== 'string') return null;
    out.push({ lang: t.lang, codec: t.codec, channels: typeof t.channels === 'number' ? t.channels : 0 });
  }
  return out;
}

function itemOf(value: unknown): LabMediaItem | null {
  if (!isObject(value) || typeof value.url !== 'string' || !/^https?:\/\//.test(value.url)) return null;
  const kind = value.kind === 'live' || value.kind === 'vod' ? value.kind : null;
  const container = value.container === 'ts' || value.container === 'hls' || value.container === 'mp4' || value.container === 'mkv' ? value.container : null;
  if (kind === null || container === null) return null;
  const video = isObject(value.video) && typeof value.video.codec === 'string' && typeof value.video.width === 'number' && typeof value.video.height === 'number' ? { codec: value.video.codec, width: value.video.width, height: value.video.height } : null;
  const subtitles = trackList(value.subtitles);
  return {
    url: value.url,
    kind,
    container,
    fault: typeof value.fault === 'string' ? value.fault : null,
    video,
    audio: trackList(value.audio),
    subtitles: subtitles === null ? null : subtitles.map((s) => ({ lang: s.lang, codec: s.codec })),
  };
}

/** The answer, or null when it isn't one; items that don't parse are left out. */
export function parseLabMedia(value: unknown): LabMedia | null {
  if (!isObject(value) || typeof value.media !== 'string' || !isObject(value.items)) return null;
  const items: Partial<Record<LabMediaId, LabMediaItem>> = {};
  for (const id of LAB_MEDIA_IDS) {
    const item = itemOf(value.items[id]);
    if (item !== null) items[id] = item;
  }
  return { media: value.media, items };
}

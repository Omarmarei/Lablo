describe('SubtitleParser limits', () => {
  it('skips lines longer than maxLineLength, wherever the chunks split them', () => {
    const long = 'x'.repeat(40);
    const fits = 'z'.repeat(32);
    const text = `1\n00:00:01,000 --> 00:00:02,000\n${long}\nshort\n${fits}\n\n2\n00:00:03,000 --> 00:00:04,000\n${long}`;
    const expected: ParsedSubtitles = {
      format: 'srt',
      cues: [cue(1000, 2000, `short\n${fits}`)],
      stats: stats({ lines: 9, cues: 1, overlongLines: 2, emptyCues: 1 }),
    };
    expect(parseSubtitles(text, { maxLineLength: 32 })).toEqual(expected);
    // One character at a time: a line of exactly 32 waits whole for its line end.
    expect(parseChunks(text.split(''), { maxLineLength: 32 })).toEqual(expected);
    fc.assert(
      fc.property(fc.array(fc.nat(), { maxLength: 10 }), (cuts) => {
        expect(parseChunks(split(text, cuts), { maxLineLength: 32 })).toEqual(expected);
      }),
    );
  });

  it('counts a line many times over maxLineLength once, holding none of it, however it arrives', () => {
    const text = `00:00:01,000 --> 00:00:02,000\n${'w'.repeat(100)}\nkept`;
    const expected = { cues: [cue(1000, 2000, 'kept')], stats: stats({ lines: 3, cues: 1, overlongLines: 1 }) };
    expect(parseChunks(text.split(''), { maxLineLength: 32 })).toMatchObject(expected);
    expect(parseChunks(['00:00:01,000 --> 00:00:02,000\n', 'w'.repeat(40), 'w'.repeat(40), 'w'.repeat(20), '\nkept'], { maxLineLength: 32 })).toMatchObject(expected);
  });

  it('keeps maxCues cues and counts the rest', () => {
    let text = '';
    for (let i = 0; i < 5; i++) text += `${i + 1}\n00:00:0${i},000 --> 00:00:0${i},500\nCue ${i}\n\n`;
    const parsed = parseSubtitles(text, { maxCues: 3 });
    expect(parsed.cues.map((c) => c.text)).toEqual(['Cue 0', 'Cue 1', 'Cue 2']);
    expect(parsed.stats).toMatchObject({ cues: 3, droppedCues: 2 });
  });

  it('stops collecting a cue’s text at maxLineLength code units and cuts it to MAX_CUE_TEXT', () => {
    const line = 'y'.repeat(900);
    let text = '00:00:01,000 --> 00:00:02,000\n';
    for (let i = 0; i < 50; i++) text += `${line}\n`;
    const parsed = parseSubtitles(text, { maxLineLength: 2000 });
    // Three lines are collected (900, 1800, then 2700 > 2000 stops it); the text is cut.
    expect(parsed.cues[0]!.text).toBe(`${line}\n${line}\n${'y'.repeat(MAX_CUE_TEXT - 1802)}`);
  });

  it('collects a cue’s lines while it holds at most maxLineLength code units', () => {
    const line = 'abcdefghij';
    const text = `00:00:01,000 --> 00:00:02,000\n${`${line}\n`.repeat(6)}`;
    // 0, 10, 20 and 30 code units held: four lines are kept.
    expect(parseSubtitles(text, { maxLineLength: 30 }).cues[0]!.text).toBe(`${line}\n${line}\n${line}\n${line}`);
  });

  it('throws on push() after end(), and end() twice gives nothing', () => {
    const parser = new SubtitleParser();
    parser.push('00:00:01,000 --> 00:00:02,000\nHi');
    expect(parser.end()).toEqual([cue(1000, 2000, 'Hi')]);
    expect(parser.end()).toEqual([]);
    expect(() => parser.push('more')).toThrow();
  });
});


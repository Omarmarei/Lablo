const BOM = String.fromCharCode(0xfeff);
const NBSP = String.fromCharCode(0xa0);
const LRM = String.fromCharCode(0x200e);
const RLM = String.fromCharCode(0x200f);
const BS = String.fromCharCode(92);

function parseChunks(chunks: string[], options?: SubtitleParserOptions): ParsedSubtitles {
  const parser = new SubtitleParser(options);
  const cues: SubtitleCue[] = [];
  for (const chunk of chunks) cues.push(...parser.push(chunk));
  cues.push(...parser.end());
  return { format: parser.format, cues, stats: parser.stats };
}

/** Splits `text` at the given offsets (any order; repeated offsets give empty chunks). */
function split(text: string, cuts: number[]): string[] {
  const points = cuts.map((c) => c % (text.length + 1)).sort((a, b) => a - b);
  const out: string[] = [];
  let last = 0;
  for (const p of points) {
    out.push(text.slice(last, p));
    last = p;
  }
  out.push(text.slice(last));
  return out;
}

const cue = (startMs: number, endMs: number, text: string): SubtitleCue => ({ startMs, endMs, text });

const stats = (s: Partial<SubtitleStats> & Pick<SubtitleStats, 'lines' | 'cues'>): SubtitleStats => ({
  badTimings: 0,
  junk: 0,
  emptyCues: 0,
  overlongLines: 0,
  droppedCues: 0,
  ...s,
});

/**
 * The lines joined with `\n`, `\r\n` and `\r` in turn; no line end after the last one. A `\r`
 * before an empty line would become a CRLF with that line's `\n` (losing the blank line), so
 * that one gets `\n`.
 */
function joinLines(lines: readonly string[]): string {
  let text = '';
  for (let i = 0; i < lines.length; i++) {
    text += lines[i];
    if (i === lines.length - 1) break;
    const kind = i % 3;
    text += kind === 0 ? '\n' : kind === 1 ? '\r\n' : lines[i + 1] === '' ? '\n' : '\r';
  }
  return text;
}


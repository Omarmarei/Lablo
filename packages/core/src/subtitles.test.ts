function wellFormed(parsed: ParsedSubtitles): void {
  expect(parsed.stats.cues).toBe(parsed.cues.length);
  for (const c of parsed.cues) {
    expect(Number.isInteger(c.startMs) && c.startMs >= 0).toBe(true);
    expect(c.endMs).toBeGreaterThan(c.startMs);
    expect(c.text.length).toBeGreaterThan(0);
    expect(c.text.length).toBeLessThanOrEqual(MAX_CUE_TEXT);
    for (const line of c.text.split('\n')) expect(line === line.trim() && line !== '').toBe(true);
  }
}

describe('SubtitleParser properties', () => {
  it('never throws, gives well-formed cues, and reads any chunking alike', () => {
    fc.assert(
      fc.property(subtitleText, fc.array(fc.nat(), { maxLength: 8 }), fc.constantFrom<'srt' | 'vtt'>('srt', 'vtt'), (text, cuts, format) => {
        const whole = parseSubtitles(text, { format });
        wellFormed(whole);
        expect(parseChunks(split(text, cuts), { format })).toEqual(whole);
        expect(() => cueText(text)).not.toThrow();
      }),
      { numRuns: 1500 },
    );
  });

  const WORD = fc.constantFrom('Hello', 'world', 'مرحبا', 'بكم', '٣', 'a,b', '"quoted"', 'x-y', 'line', '7');
  const LINE = fc.array(WORD, { minLength: 1, maxLength: 4 }).map((w) => w.join(' '));
  /** Cues of 1 to 3 lines; times in centiseconds (ASS's precision), up to 10 h. */
  const CUES = fc.array(
    fc.record({
      start: fc.integer({ min: 0, max: 3_600_000 }),
      length: fc.integer({ min: 1, max: 1000 }),
      lines: fc.array(LINE, { minLength: 1, maxLength: 3 }),
    }),
    { maxLength: 20 },
  );

  const pad = (n: number, w = 2): string => String(n).padStart(w, '0');
  const clock = (ms: number, sep: string, hours: boolean): string => {
    const h = Math.floor(ms / 3_600_000);
    const m = Math.floor(ms / 60_000) % 60;
    const s = Math.floor(ms / 1000) % 60;
    return `${hours || h > 0 ? `${pad(h)}:` : ''}${pad(m)}:${pad(s)}${sep}${pad(ms % 1000, 3)}`;
  };
  const assClock = (ms: number): string => `${Math.floor(ms / 3_600_000)}:${pad(Math.floor(ms / 60_000) % 60)}:${pad(Math.floor(ms / 1000) % 60)}.${pad((ms % 1000) / 10)}`;

  it('reads back what SRT, WebVTT and ASS writers wrote, in any chunks', () => {
    fc.assert(
      fc.property(CUES, fc.constantFrom('\n', '\r\n', '\r'), fc.array(fc.nat(), { maxLength: 8 }), (spec, nl, cuts) => {
        const cues = spec.map((c) => cue(c.start * 10, (c.start + c.length) * 10, c.lines.join('\n')));
        const srt = cues.map((c, i) => `${i + 1}${nl}${clock(c.startMs, ',', true)} --> ${clock(c.endMs, ',', true)}${nl}${c.text.split('\n').join(nl)}${nl}`).join(nl);
        const vtt = `WEBVTT${nl}${nl}${cues.map((c) => `${clock(c.startMs, '.', false)} --> ${clock(c.endMs, '.', false)} line:90%${nl}${c.text.split('\n').join(nl)}${nl}`).join(nl)}`;
        const ass = `[Script Info]${nl}ScriptType: v4.00+${nl}${nl}[Events]${nl}Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text${nl}${cues
          .map((c) => `Dialogue: 0,${assClock(c.startMs)},${assClock(c.endMs)},Default,,0,0,0,,${c.text.split('\n').join(`${BS}N`)}${nl}`)
          .join('')}`;
        for (const [text, format] of [
          [srt, 'srt'],
          [vtt, 'vtt'],
          [ass, 'ass'],
        ] as const) {
          const parsed = parseChunks(split(text, cuts));
          expect(parsed.cues).toEqual(cues);
          expect(parsed.format).toBe(cues.length === 0 && format === 'srt' ? null : format);
          expect(parsed.stats).toMatchObject({ badTimings: 0, junk: 0, emptyCues: 0 });
        }
      }),
      { numRuns: 300 },
    );
  });
});

describe('SubtitleTrack', () => {
  it('sorts by start, keeping the file’s order for equal starts', () => {
    const track = new SubtitleTrack([cue(3000, 4000, 'c'), cue(1000, 2000, 'a1'), cue(1000, 5000, 'a2'), cue(2000, 2500, 'b')]);
    expect(track.cues.map((c) => c.text)).toEqual(['a1', 'a2', 'b', 'c']);
  });

  it('shows a cue from its start up to (not at) its end, and none before the first or between cues', () => {
    const track = new SubtitleTrack([cue(1000, 2000, 'a'), cue(3000, 4000, 'b')]);
    expect(track.cuesAt(999)).toEqual([]);
    expect(track.cuesAt(1000)).toEqual([cue(1000, 2000, 'a')]);
    expect(track.cuesAt(1999)).toEqual([cue(1000, 2000, 'a')]);
    expect(track.cuesAt(2000)).toEqual([]);
    expect(track.cuesAt(2500)).toEqual([]);
    expect(track.cuesAt(4000)).toEqual([]);
    expect(new SubtitleTrack([]).cuesAt(0)).toEqual([]);
  });

  it('finds a long cue behind short ones that ended', () => {
    const track = new SubtitleTrack([cue(0, 100_000, 'sign'), cue(1000, 2000, 'a'), cue(3000, 4000, 'b')]);
    expect(track.cuesAt(3500).map((c) => c.text)).toEqual(['sign', 'b']);
    expect(track.cuesAt(2500).map((c) => c.text)).toEqual(['sign']);
  });

  it('matches a filter of the sorted cues, without repeated text', () => {
    const CUE = fc.record({ start: fc.integer({ min: 0, max: 60 }), length: fc.integer({ min: 1, max: 30 }), text: fc.constantFrom('a', 'b', 'c', 'd') });
    fc.assert(
      fc.property(fc.array(CUE, { maxLength: 30 }), fc.integer({ min: -5, max: 100 }), (spec, ms) => {
        const cues = spec.map((c) => cue(c.start, c.start + c.length, c.text));
        const sorted = cues
          .map((c, i) => ({ c, i }))
          .sort((x, y) => x.c.startMs - y.c.startMs || x.i - y.i)
          .map((x) => x.c);
        const expected: SubtitleCue[] = [];
        for (const c of sorted) if (c.startMs <= ms && ms < c.endMs && !expected.some((e) => e.text === c.text)) expected.push(c);
        const track = new SubtitleTrack(cues);
        expect(track.cues).toEqual(sorted);
        expect(track.cuesAt(ms)).toEqual(expected);
      }),
      { numRuns: 1000 },
    );
  });
});
